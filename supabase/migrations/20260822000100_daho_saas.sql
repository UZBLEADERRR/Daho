create or replace function public.admin_stats()
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select case when not public.is_admin() then '{}'::jsonb else jsonb_build_object(
    'users',        (select count(*) from public.profiles),
    'paid_users',   (select count(*) from public.profiles p
                       join public.plans pl on pl.code = p.plan_code
                      where pl.rank > 0
                        and (p.plan_expires_at is null or p.plan_expires_at > now())),
    'pending',      (select count(*) from public.subscription_requests where status = 'pending'),
    'tokens_month', (select coalesce(sum(billed_tokens), 0) from public.usage_events
                      where created_at >= date_trunc('month', now())),
    'tokens_today', (select coalesce(sum(billed_tokens), 0) from public.usage_events
                      where created_at >= date_trunc('day', now())),
    'top_models',   (select coalesce(jsonb_agg(t), '[]'::jsonb) from (
                        select model_slug as slug, sum(billed_tokens)::bigint as tokens
                          from public.usage_events
                         where created_at >= date_trunc('month', now())
                         group by model_slug order by 2 desc limit 8
                      ) t)
  ) end;
$$;

