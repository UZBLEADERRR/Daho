-- Joriy foydalanuvchi admin mi. RLS ichida ishlatilgani uchun
-- security definer — aks holda profiles ustidagi siyosat oʻzini chaqirib
-- cheksiz rekursiyaga tushadi.
create or replace function public.is_admin()
returns bool
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    (select p.role = 'admin' from public.profiles p where p.id = auth.uid()),
    false
  );
$$;

-- Foydalanuvchining amaldagi tarif darajasi.
-- Muddati oʻtgan obuna avtomatik bepulga tushadi.
create or replace function public.plan_rank_of(uid uuid)
returns int
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    (
      select case
               when p.plan_expires_at is not null and p.plan_expires_at < now() then 0
               else coalesce(pl.rank, 0)
             end
      from public.profiles p
      left join public.plans pl on pl.code = p.plan_code
      where p.id = uid
    ),
    0
  );
$$;

-- Yangi foydalanuvchi roʻyxatdan oʻtganda profil ochiladi.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  owners jsonb;
  is_owner bool := false;
begin
  -- Egasining pochtasi app_settings da turadi: u roʻyxatdan oʻtishi bilan
  -- avtomatik admin boʻladi, SQL ni qoʻlda yozish shart emas.
  select value into owners from public.app_settings where key = 'owner_emails';
  if owners is not null then
    is_owner := exists (
      select 1 from jsonb_array_elements_text(owners) e
      where lower(e) = lower(coalesce(new.email, ''))
    );
  end if;

  insert into public.profiles (id, email, full_name, role)
  values (
    new.id,
    coalesce(new.email, ''),
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    case when is_owner then 'admin' else 'user' end
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

