-- Oylik kvota holati. Oy almashgan boʻlsa hisob nolga tushgan deb koʻrsatiladi
-- (haqiqiy nolga tushirishni AI proxy yozuv paytida bajaradi).
create or replace function public.quota_state()
returns table (
  plan_code text,
  plan_name text,
  plan_rank int,
  monthly_tokens bigint,
  tokens_used bigint,
  tokens_left bigint,
  period_start timestamptz,
  resets_at timestamptz,
  plan_expires_at timestamptz
)
language sql
stable
security definer
set search_path = public
as $$
  select
    p.plan_code,
    coalesce(pl.name, 'Bepul'),
    public.plan_rank_of(p.id),
    coalesce(pl.monthly_tokens, 0),
    case when p.period_start < date_trunc('month', now()) then 0 else p.tokens_used end,
    greatest(
      coalesce(pl.monthly_tokens, 0)
        - case when p.period_start < date_trunc('month', now()) then 0 else p.tokens_used end,
      0
    ),
    p.period_start,
    date_trunc('month', now()) + interval '1 month',
    p.plan_expires_at
  from public.profiles p
  left join public.plans pl on pl.code = p.plan_code
  where p.id = auth.uid();
$$;

